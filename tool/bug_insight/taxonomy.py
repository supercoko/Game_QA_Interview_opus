def match_tags(text: str, tags: list[Tag]) -> list[str]:
    # 一条文本可同时匹配多条规则；返回的是规则 id 列表，而不是互斥的单一标签。
    return [t.id for t in tags if t.match(text)]


def severity(symptoms: list[str], text: str) -> str:
    # 严重度按优先级依次判断：阻断 > 功能数据 > 表现界面音频 > 文本 > 未识别。
    display_only = bool(re.search(r"不影响实际(技能)?效果|实际效果不变|该问题不影响", text))
    if "block" in symptoms or ("perf" in symptoms and re.search(r"闪退|崩溃|无法进入游戏", text)):
        return "S1"
    if not display_only and ("logic" in symptoms or "economy" in symptoms):
        return "S2"
    if any(s in symptoms for s in ("visual", "ui", "audio", "perf")):
        return "S3"
    if "text" in symptoms:
        return "S4"
    if display_only:
        return "S3"
    return "S?"


def normalize_module(category: str, text: str) -> str:
    module = CATEGORY_TO_MODULE.get(category)
    if module:
        return module
    for name, pat in FALLBACK_RULES:
        if pat.search(text):
            return name
    return "其他/综合"


