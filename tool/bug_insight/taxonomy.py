"""缺陷分类规则。

三个维度，都是基于关键词正则的启发式规则（多标签）：

1. 触发维度 TRIGGERS —— 「在什么条件下才会出问题」，直接对应测试设计方法；
2. 现象类型 SYMPTOMS —— 「出了什么问题」，用于推断严重度；
3. 归一化模块 —— 把四个游戏各不相同的公告分类映射成统一模块。

规则是启发式的，精度靠人工抽检评估（见 方案/01 文档），
不要把统计结果当成精确值，而是当成「风险分布的近似画像」。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Tag:
    id: str
    name: str
    pattern: re.Pattern
    exclude: re.Pattern | None = None
    technique: str = ""      # 对应的测试设计方法
    detection: str = ""      # 更适合用什么手段发现
    hint: str = ""           # 写测试点时的提问方式

    def match(self, text: str) -> bool:
        if not self.pattern.search(text):
            return False
        if self.exclude and self.exclude.search(text):
            # 先检测到排除词，再把排除词片段删掉；如果该片段之前只是触发词，
            # 删除后不再命中 pattern 时，本条规则仍会判定为不匹配。
            stripped = self.exclude.sub("", text)
            return bool(self.pattern.search(stripped))
        return True


def _re(s: str) -> re.Pattern:
    return re.compile(s)


